# ch02.md의 "실습 2-6. 종합"의 요구 사항을 2장까지 배운 문법만으로
# 구현한 것이다. 리스트나 함수 없이 변수, 조건문, 반복문만 사용한다.

# 반복 전에 결과를 쌓아 갈 변수를 준비한다(누적 패턴, 2.5.2).
total = 0
count = 0
best_score = 0
best_name = None  # 아직 아무도 입력하지 않았다는 뜻(2.1.6)

# 바깥쪽 반복: 이름을 묻는다. 빈 이름이 들어오면 끝낸다.
while True:
    name = input("이름 (끝내려면 Enter): ").strip()
    if not name:  # 빈 문자열은 거짓이다(2.4.5)
        break

    # 안쪽 반복: 올바른 점수가 들어올 때까지 점수만 다시 묻는다.
    while True:
        score_text = input("점수: ").strip()
        # isdigit()가 참일 때만 int()로 바꾸므로 "백점" 같은 입력에서
        # ValueError가 나지 않는다.
        if score_text.isdigit():
            score = int(score_text)
            if 0 <= score <= 100:  # 연속 비교(2.2.3)
                break  # 안쪽 반복만 끝난다(2.5.5)
        print("  0~100 사이의 정수를 입력하세요.")

    # 좁은 조건부터 차례로 검사한다(2.4.3).
    if score >= 90:
        grade = "A"
    elif score >= 80:
        grade = "B"
    elif score >= 70:
        grade = "C"
    else:
        grade = "F"
    print(f"  → {name}: {score}점, {grade}")

    total += score
    count += 1

    # 첫 학생이면(best_name is None) 점수와 상관없이 기록한다.
    # 이 검사가 없으면 첫 학생이 0점일 때 0 > 0이 거짓이라 기록되지 않는다.
    # `>`를 쓰므로 동점이면 먼저 입력한 학생이 남는다.
    if best_name is None or score > best_score:
        best_score = score
        best_name = name

# 학생 수가 0이면 평균을 계산하지 않는다(0으로 나누기 방지, 2.2.1).
if count == 0:
    print("입력된 학생이 없습니다.")
else:
    average = total / count
    print("=" * 24)
    print(f"학생 수: {count}명")
    print(f"평균: {average:.1f}점")
    print(f"최고 점수: {best_name} ({best_score}점)")
    print("=" * 24)


