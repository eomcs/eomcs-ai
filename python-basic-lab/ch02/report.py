#    count가 0이므로 "입력된 학생이 없습니다."만 출력된다.
#    학생 1명: 그 학생이 그대로 최고 점수가 되고, 평균은 그 학생의 점수다.
#
# 2. 점수 입력에 대한 동작
#    -5   : "-"는 숫자가 아니므로 isdigit()가 거짓이다. 다시 묻는다.
#    3.5  : "."는 숫자가 아니므로 isdigit()가 거짓이다. 다시 묻는다.
#     90  : strip()으로 앞뒤 공백을 지운 뒤 검사하므로 90점으로 처리된다.
#           strip()을 빼면 공백 때문에 isdigit()가 거짓이 되어 다시 묻는다.
#    음수와 실수는 범위 밖이거나 정수가 아니므로, 다시 묻는 것이
#    요구 사항에 맞는 동작이다.
#
#    참고: isdigit()는 "²"나 "①" 같은 특수 숫자 문자도 숫자로 보기 때문에
#    이런 문자를 입력하면 int()에서 ValueError가 난다. 일반 키보드 입력에서는
#    거의 생기지 않는 경우이며, 6장 "예외"의 try/except로 완전히 막을 수 있다.
#
# 3. 동점인 최고 점수가 있으면 먼저 입력한 학생이 출력된다.
#    score > best_score는 더 큰 점수일 때만 참이므로, 같은 점수의 학생이
#    나중에 들어와도 best_name이 바뀌지 않는다. >=로 바꾸면 같은 점수일 때도
#    참이 되어 나중에 입력한 학생으로 바뀐다.
